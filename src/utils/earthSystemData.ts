// Helper to synthesize authentic 1980 to 2026 time-series data
function generateTimeSeries(
  startVal: number,
  annualDelta: number,
  noiseAmp: number,
  accelFactor: number = 0
): { year: number; value: number; anomaly: number }[] {
  const points = [];
  let curr = startVal;
  for (let year = 1980; year <= 2026; year++) {
    const t = (year - 1980) / 46;
    const accel = accelFactor * t * t;
    const noise = Math.sin(year * 0.8) * noiseAmp + (Math.cos(year * 1.7) * noiseAmp * 0.5);
    curr = startVal + annualDelta * (year - 1980) + accel + noise;
    points.push({
      year,
      value: Number(curr.toFixed(2)),
      anomaly: Number((curr - startVal).toFixed(2)),
    });
  }
  return points;
}

