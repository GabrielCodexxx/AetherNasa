import type { LevelConfig, TileType } from '../types/trainer';

// Helper to quickly build 8x8 or 10x10 grids with basalt defaults
function createGrid(w: number, h: number, overrides: Record<string, TileType>): TileType[][] {
  const grid: TileType[][] = [];
  for (let r = 0; r < h; r++) {
    const row: TileType[] = [];
    for (let c = 0; c < w; c++) {
      const key = `${r},${c}`;
      row.push(overrides[key] || 'basalt');
    }
    grid.push(row);
  }
  return grid;
}

