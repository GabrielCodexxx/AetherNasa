// Helper to synthesize realistic decaying seismogram waveforms
function generateWaveform(type: string, mag: number): number[] {
  const points: number[] = [];
  const length = 60;
  for (let i = 0; i < length; i++) {
    const t = i / length;
    // Moonquakes have extremely slow rise and prolonged ringing
    const envelope = Math.sin(t * Math.PI) * Math.exp(-t * (type === 'shallow' ? 1.2 : 2.5));
    const noise = (Math.sin(i * 1.7) + Math.cos(i * 3.4) + (Math.random() - 0.5) * 0.4);
    points.push(Number((noise * envelope * mag * 18).toFixed(1)));
  }
  return points;
}

